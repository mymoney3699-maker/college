// ============================================================
// دالة إضافة صفوف إضافية للجدول
// ============================================================
function إضافة_صفوف(العدد) {
    const جسم = document.getElementById('جسم-الجدول');
    if (!جسم) {
        console.warn('⚠️ عنصر جسم الجدول غير موجود');
        return;
    }

    const الصفوف_الحالية = جسم.querySelectorAll('tr').length;
    const العدد_الجديد = الصفوف_الحالية + العدد;

    for (let i = الصفوف_الحالية + 1; i <= العدد_الجديد; i++) {
        const صف = document.createElement('tr');
        صف.innerHTML = `
            <td></td>
            <td></td>
            <td></td>
            <td></td>
        `;
        جسم.appendChild(صف);
    }

    console.log(`✅ تم إضافة ${العدد} صفوف جديدة، العدد الإجمالي: ${العدد_الجديد}`);
}

// ============================================================
// دالة إعادة تعيين الجدول إلى 16 صفاً
// ============================================================
function إعادة_تعيين_الجدول() {
    const جسم = document.getElementById('جسم-الجدول');
    if (!جسم) {
        console.warn('⚠️ عنصر جسم الجدول غير موجود');
        return;
    }

    جسم.innerHTML = '';
    for (let i = 1; i <= 16; i++) {
        const صف = document.createElement('tr');
        صف.innerHTML = `
            <td></td>
            <td></td>
            <td></td>
            <td></td>
        `;
        جسم.appendChild(صف);
    }

    console.log('✅ تم إعادة تعيين الجدول إلى 16 صفاً');
}

// ============================================================
// دالة حذف آخر صف من الجدول
// ============================================================
function حذف_آخر_صف() {
    const جسم = document.getElementById('جسم-الجدول');
    if (!جسم) {
        console.warn('⚠️ عنصر جسم الجدول غير موجود');
        return;
    }

    const الصفوف = جسم.querySelectorAll('tr');
    if (الصفوف.length <= 1) {
        console.warn('⚠️ لا يمكن حذف الصف الأخير');
        return;
    }

    الصفوف[الصفوف.length - 1].remove();
    const الصفوف_المتبقية = جسم.querySelectorAll('tr');

    console.log(`✅ تم حذف آخر صف، العدد المتبقي: ${الصفوف_المتبقية.length}`);
}

// ============================================================
// دالة طباعة البيانات (في حال التطوير المستقبلي)
// ============================================================
function طباعة_البيانات() {
    const جسم = document.getElementById('جسم-الجدول');
    if (!جسم) return;

    const الصفوف = جسم.querySelectorAll('tr');
    const البيانات = [];

    الصفوف.forEach((صف) => {
        const الخلايا = صف.querySelectorAll('td');
        البيانات.push({
            رقم: الخلايا[0]?.textContent || '',
            قيد: الخلايا[1]?.textContent || '',
            اسم: الخلايا[2]?.textContent || '',
            توقيع: الخلايا[3]?.textContent || ''
        });
    });

    console.log('📊 بيانات الجدول:', البيانات);
    return البيانات;
}

